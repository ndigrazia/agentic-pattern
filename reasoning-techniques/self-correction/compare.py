"""Comparison runner: Standalone Self-Correction Agent vs Two-Stage Workflow.

Demonstrates the operational and behavioral differences between:
1. Alternative 1: Standalone Agent (Human provides Requirements + Draft; agent reviews & refines)
2. Alternative 2: Multi-Agent Workflow (Human provides Requirements only; DraftWriter generates, Critic refines)
"""

from __future__ import annotations

import argparse
import asyncio
from pathlib import Path
import sys
from typing import Optional

# Ensure package directory is in sys.path
base_dir = Path(__file__).resolve().parent
if str(base_dir) not in sys.path:
    sys.path.insert(0, str(base_dir))

from self_correction_agent import (
    create_self_correction_agent,
    create_self_correction_workflow,
    get_default_model,
)
from main import run_agent_query, format_user_query, DEFAULT_PROMPT_CASE


async def compare_alternatives(
    requirements: str,
    draft: str,
    model_name: Optional[str] = None,
) -> None:
    """Executes and compares Standalone Agent vs Multi-Agent Workflow side by side."""
    model = model_name or get_default_model()

    print("\n" + "=" * 80)
    print("⚖️  COMPARISON: Standalone Agent vs Two-Stage Workflow")
    print("=" * 80)
    print(f"📋 Requirements:\n   \"{requirements}\"")
    print(f"📝 Human Draft (Used by Standalone Agent):\n   \"{draft}\"")
    print(f"🤖 Model: {model}")
    print("=" * 80 + "\n")

    # =========================================================================
    # Alternative 1: Standalone Self-Correction Agent
    # =========================================================================
    print("━" * 80)
    print("🔵 ALTERNATIVE 1: Standalone Self-Correction Agent (`self_correction_agent`)")
    print("━" * 80)
    print("• Architecture: Single LlmAgent acting as an expert editor/critic.")
    print("• Role: Reviews human-supplied draft against requirements.")
    print("• Execution Flow: User (Req + Draft) ──► [self_correction_agent] ──► Final Polish\n")

    agent = create_self_correction_agent(model_name=model, mode="few-shot")
    agent_query = format_user_query(requirements, draft)

    agent_result = await run_agent_query(agent, agent_query, verbose=True)

    # =========================================================================
    # Alternative 2: Autonomous Multi-Agent Workflow
    # =========================================================================
    print("\n" + "━" * 80)
    print("🟢 ALTERNATIVE 2: Two-Stage Autonomous Workflow (`self_correction_pipeline`)")
    print("━" * 80)
    print("• Architecture: ADK Workflow connecting DraftWriter ──► SelfCorrectionCritic.")
    print("• Role: Autonomous end-to-end generation and self-correction.")
    print("• Execution Flow: User (Req only) ──► [DraftWriter] ──► state ──► [SelfCorrectionCritic] ──► Final Polish\n")

    workflow = create_self_correction_workflow(model_name=model)
    workflow_query = (
        f"Requirements: {requirements}\n"
        f"Please generate an initial draft, then critically review and self-correct it."
    )
    workflow_state = {"original_requirements": requirements}

    workflow_result = await run_agent_query(
        workflow, workflow_query, verbose=True, initial_state=workflow_state
    )

    # =========================================================================
    # Side-by-Side Comparison Matrix
    # =========================================================================
    print("\n" + "=" * 80)
    print("📊 COMPARISON SUMMARY & METRICS")
    print("=" * 80)

    print(f"{'Feature / Metric':<30} | {'Alternative 1: Standalone Agent':<23} | {'Alternative 2: Workflow Pipeline'}")
    print("-" * 80)
    print(f"{'Structure':<30} | {'Single LlmAgent':<23} | {'Two-Stage Workflow Graph'}")
    print(f"{'Draft Origin':<30} | {'Supplied by User':<23} | {'Auto-generated by DraftWriter'}")
    print(f"{'LLM Agent Calls':<30} | {'1 Agent':<23} | {'2 Agents (Writer + Critic)'}")
    print(f"{'Session State Storage':<30} | {'None / Minimal':<23} | {'draft_content & corrected_content'}")
    agent_time = f"{agent_result['elapsed_seconds']}s"
    workflow_time = f"{workflow_result['elapsed_seconds']}s"
    print(f"{'Execution Latency':<30} | {agent_time:<23} | {workflow_time}")
    print(f"{'Best For':<30} | {'Refining existing drafts':<23} | {'Autonomous content creation'}")
    print("=" * 80 + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Compare Standalone Agent vs Multi-Agent Workflow in Self-Correction"
    )
    parser.add_argument(
        "-r", "--requirements",
        type=str,
        default=DEFAULT_PROMPT_CASE["requirements"],
        help="Prompt requirements",
    )
    parser.add_argument(
        "-d", "--draft",
        type=str,
        default=DEFAULT_PROMPT_CASE["draft"],
        help="Initial draft for Alternative 1",
    )
    parser.add_argument(
        "--model",
        type=str,
        default=None,
        help="Gemini model override",
    )

    args = parser.parse_args()
    asyncio.run(compare_alternatives(args.requirements, args.draft, model_name=args.model))


if __name__ == "__main__":
    main()
