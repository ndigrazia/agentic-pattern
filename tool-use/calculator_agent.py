import os
import uuid
import asyncio
from dotenv import load_dotenv
import nest_asyncio

from google.adk.agents import Agent
from google.adk.code_executors import BuiltInCodeExecutor
from google.adk.runners import InMemoryRunner
from google.genai import types

load_dotenv()

# Define variables required for Session setup and Agent execution
APP_NAME = "calculator_agent"
GEMINI_MODEL = os.getenv("GEMINI_MODEL_NAME", "gemini-3.5-flash")

# Define Agent with access to Python code execution tool
root_agent = Agent(
    name="calculator_agent",
    model=GEMINI_MODEL,
    description="Executes Python code to perform calculations and solve mathematical problems.",
    instruction="""You are a calculator agent. When given a mathematical or computational question,
    write and execute Python code using the code executor to calculate the result.
    Provide the final answer clearly and concisely based on the execution result.
    """,
    code_executor=BuiltInCodeExecutor(),
)


# Agent Interaction
async def call_agent(runner: InMemoryRunner, query: str) -> str:
    """Function to call the agent with a query and return the response."""
    print(f"\n--- 🏃 Running Query: '{query}' ---")
    final_result = ""
    try:
        user_id = "user_123"
        session_id = str(uuid.uuid4())

        await runner.session_service.create_session(
            app_name=runner.app_name,
            user_id=user_id,
            session_id=session_id,
        )

        msg = types.Content(
            role="user",
            parts=[types.Part.from_text(text=query)],
        )

        async for event in runner.run_async(
            user_id=user_id,
            session_id=session_id,
            new_message=msg,
        ):
            if event.content and event.content.parts:
                for part in event.content.parts:
                    # Display code generated by the agent tool
                    if getattr(part, "executable_code", None) and part.executable_code.code:
                        print(f"⚙️  [Generated Code]:\n{part.executable_code.code.strip()}")
                    # Display tool execution output
                    if getattr(part, "code_execution_result", None) and part.code_execution_result.output:
                        print(f"💻 [Execution Result]: {part.code_execution_result.output.strip()}")

            if event.is_final_response() and event.content:
                if hasattr(event.content, "text") and event.content.text:
                    final_result = event.content.text
                elif event.content.parts:
                    text_parts = [p.text for p in event.content.parts if p.text]
                    final_result = "".join(text_parts).strip()

        print(f"✅ Agent Response: {final_result}")
        return final_result
    except Exception as e:
        print(f"🛑 An error occurred while processing your request: {e}")
        return f"An error occurred while processing your request: {e}"


async def main():
    """Main function to run the ADK tool use (code executor) example."""
    print("--- Google ADK Tool Use Example (Code Executor) ---")
    runner = InMemoryRunner(root_agent, app_name=APP_NAME)

    # Example Queries
    await call_agent(runner, "What is the result of 12345 * 6789?")
    await call_agent(runner, "Calculate the 15th Fibonacci number.")


if __name__ == "__main__":
    nest_asyncio.apply()
    asyncio.run(main())

