"""Inter-Process Communication (IPC) Authorization Store for Human-in-the-Loop.

Provides a persistent, concurrent SQLite-backed store for managing authorization
requests between an Agent process (in ADK Web or CLI) and a Human Supervisor process.
"""

from __future__ import annotations

import asyncio
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
import json
import logging
import os
from pathlib import Path
import sqlite3
from typing import Any, Dict, List, Optional
import uuid

logger = logging.getLogger("HITL3.IPCStore")
DEFAULT_DB_FILENAME = "hitl_auth_requests.db"


@dataclass
class AuthorizationRequest:
    """Represents an authorization request generated by an agent and reviewed by a supervisor."""

    request_id: str
    session_id: str
    user_id: str
    function_call_id: str
    tool_name: str
    tool_args: Dict[str, Any]
    agent_pid: int
    status: str  # "PENDING", "APPROVED", "REJECTED", "EXPIRED"
    supervisor_notes: str = ""
    supervisor_pid: Optional[int] = None
    created_at: str = ""
    decided_at: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class IPCAuthorizationStore:
    """Thread-safe and process-safe authorization request store backed by SQLite."""

    def __init__(self, db_path: Optional[str | Path] = None):
        if db_path is None:
            db_path = Path(__file__).parent / DEFAULT_DB_FILENAME
        self.db_path = Path(db_path)
        self._init_db()

    def _get_connection(self) -> sqlite3.Connection:
        conn = sqlite3.connect(str(self.db_path), timeout=30.0, check_same_thread=False)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA busy_timeout=10000;")
        return conn

    def _init_db(self) -> None:
        with self._get_connection() as conn:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS authorization_requests (
                    request_id TEXT PRIMARY KEY,
                    session_id TEXT NOT NULL,
                    user_id TEXT NOT NULL,
                    function_call_id TEXT NOT NULL,
                    tool_name TEXT NOT NULL,
                    tool_args TEXT NOT NULL,
                    agent_pid INTEGER NOT NULL,
                    status TEXT NOT NULL DEFAULT 'PENDING',
                    supervisor_notes TEXT DEFAULT '',
                    supervisor_pid INTEGER,
                    created_at TEXT NOT NULL,
                    decided_at TEXT
                );
                """
            )
            conn.execute("CREATE INDEX IF NOT EXISTS idx_auth_status ON authorization_requests(status);")
   
    def create_request(
        self,
        session_id: str,
        user_id: str,
        function_call_id: str,
        tool_name: str,
        tool_args: Dict[str, Any],
        agent_pid: Optional[int] = None,
    ) -> AuthorizationRequest:
        request_id = f"AUTH-{uuid.uuid4().hex[:8].upper()}"
        created_at = datetime.now(timezone.utc).isoformat()
        agent_pid = agent_pid or os.getpid()

        with self._get_connection() as conn:
            conn.execute(
                """
                INSERT INTO authorization_requests (
                    request_id, session_id, user_id, function_call_id,
                    tool_name, tool_args, agent_pid, status,
                    supervisor_notes, supervisor_pid, created_at, decided_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, 'PENDING', '', NULL, ?, NULL)
                """,
                (request_id, session_id, user_id, function_call_id, tool_name, json.dumps(tool_args), agent_pid, created_at),
            )
            conn.commit()

        logger.info("Created request %s for tool '%s' from Agent PID %s", request_id, tool_name, agent_pid)
        return AuthorizationRequest(
            request_id=request_id,
            session_id=session_id,
            user_id=user_id,
            function_call_id=function_call_id,
            tool_name=tool_name,
            tool_args=tool_args,
            agent_pid=agent_pid,
            status="PENDING",
            created_at=created_at,
        )

    def _row_to_request(self, row: sqlite3.Row) -> AuthorizationRequest:
        return AuthorizationRequest(
            request_id=row["request_id"],
            session_id=row["session_id"],
            user_id=row["user_id"],
            function_call_id=row["function_call_id"],
            tool_name=row["tool_name"],
            tool_args=json.loads(row["tool_args"]),
            agent_pid=row["agent_pid"],
            status=row["status"],
            supervisor_notes=row["supervisor_notes"] or "",
            supervisor_pid=row["supervisor_pid"],
            created_at=row["created_at"],
            decided_at=row["decided_at"],
        )

    def get_request(self, request_id: str) -> Optional[AuthorizationRequest]:
        with self._get_connection() as conn:
            cursor = conn.execute("SELECT * FROM authorization_requests WHERE request_id = ?;", (request_id,))
            row = cursor.fetchone()
            return self._row_to_request(row) if row else None

    def get_pending_requests(self) -> List[AuthorizationRequest]:
        with self._get_connection() as conn:
            cursor = conn.execute("SELECT * FROM authorization_requests WHERE status = 'PENDING' ORDER BY created_at ASC;")
            return [self._row_to_request(r) for r in cursor.fetchall()]

    def get_all_requests(self, limit: int = 50) -> List[AuthorizationRequest]:
        with self._get_connection() as conn:
            cursor = conn.execute("SELECT * FROM authorization_requests ORDER BY created_at DESC LIMIT ?;", (limit,))
            return [self._row_to_request(r) for r in cursor.fetchall()]

    def resolve_request(
        self,
        request_id: str,
        approved: bool,
        notes: str = "",
        supervisor_pid: Optional[int] = None,
    ) -> AuthorizationRequest:
        status = "APPROVED" if approved else "REJECTED"
        decided_at = datetime.now(timezone.utc).isoformat()
        supervisor_pid = supervisor_pid or os.getpid()

        with self._get_connection() as conn:
            cursor = conn.execute(
                """
                UPDATE authorization_requests
                SET status = ?, supervisor_notes = ?, supervisor_pid = ?, decided_at = ?
                WHERE request_id = ? AND status = 'PENDING';
                """,
                (status, notes, supervisor_pid, decided_at, request_id),
            )
            conn.commit()
            if cursor.rowcount == 0:
                req = self.get_request(request_id)
                if not req:
                    raise ValueError(f"Authorization request '{request_id}' not found.")
                raise ValueError(f"Request '{request_id}' is already resolved with status '{req.status}'.")

        logger.info("Resolved request %s as %s by Supervisor PID %s", request_id, status, supervisor_pid)
        return self.get_request(request_id)

    async def wait_for_decision(
        self,
        request_id: str,
        timeout_seconds: float = 60.0,
        poll_interval: float = 0.5,
    ) -> AuthorizationRequest:
        start_time = asyncio.get_event_loop().time()
        while True:
            req = self.get_request(request_id)
            if not req:
                raise ValueError(f"Authorization request '{request_id}' not found.")
            if req.status in ("APPROVED", "REJECTED"):
                return req

            elapsed = asyncio.get_event_loop().time() - start_time
            if elapsed >= timeout_seconds:
                with self._get_connection() as conn:
                    conn.execute(
                        "UPDATE authorization_requests SET status = 'EXPIRED', decided_at = ? WHERE request_id = ? AND status = 'PENDING';",
                        (datetime.now(timezone.utc).isoformat(), request_id),
                    )
                    conn.commit()
                raise TimeoutError(f"Request '{request_id}' timed out after {timeout_seconds}s waiting for supervisor.")

            await asyncio.sleep(poll_interval)

